-- RAKURS: synchronize two shared decoded signals in the existing offline archive.
-- Execute ONLY after verified full backup. Primary report = Deye slot 1.
-- Exact UTC DATETIME(6) match; no averaging, interpolation, new samples,
-- raw register modification, or modification of actual wire measurements.
-- Batch mysql must abort on the first error; never use --force.
SET SESSION sql_mode='STRICT_ALL_TABLES,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION';
SET SESSION TRANSACTION ISOLATION LEVEL SERIALIZABLE;
CREATE TEMPORARY TABLE shared_assert(ok TINYINT NOT NULL) ENGINE=InnoDB;
START TRANSACTION;
SET @d1=NULL, @d2=NULL;
SELECT MAX(CASE WHEN pm.slot_no=1 THEN pm.device_id END),
       MAX(CASE WHEN pm.slot_no=2 THEN pm.device_id END),COUNT(*)
INTO @d1,@d2,@members
FROM rakurs_parallel_members pm
JOIN rakurs_parallel_groups pg ON pg.id=pm.group_id
JOIN rakurs_devices d ON d.id=pm.device_id
WHERE pg.group_key='deye_sun20k_parallel_shared_battery'
  AND pg.battery_mode='shared' AND pg.expected_inverters=2
  AND pm.member_kind='archive' AND pm.member_verified=0 AND pm.transport_verified=0
  AND ((pm.slot_no=1 AND d.device_key='deye_inverter_1') OR
       (pm.slot_no=2 AND d.device_key='deye_inverter_2'));
SELECT COUNT(*) INTO @poll_off FROM rakurs_poll_settings WHERE id=1 AND enabled=0 FOR UPDATE;
SELECT COUNT(*) INTO @device_off FROM rakurs_device_settings
WHERE device_id IN (@d1,@d2) AND enabled=0 AND verified_connection=0 FOR UPDATE;
INSERT INTO shared_assert VALUES(IF(DATABASE()='rakurs' AND @members=2 AND @d1<>@d2
 AND @poll_off=1 AND @device_off=2,1,NULL));
SELECT 'SHARED_ARCHIVE_GUARD=PASS' AS result;
SELECT COUNT(*) INTO @signal_count FROM rakurs_signals WHERE signal_key IN ('load_power','battery_soc');
INSERT INTO shared_assert VALUES(IF(@signal_count=2,1,NULL));
SELECT COUNT(*) INTO @before_count FROM rakurs_samples m JOIN rakurs_signals s ON s.id=m.signal_id
WHERE m.device_id IN (@d1,@d2) AND s.signal_key IN ('load_power','battery_soc');
-- Only the offline archive generated by the known historical importer is writable.
SELECT COUNT(*) INTO @foreign_rows FROM rakurs_samples m JOIN rakurs_signals s ON s.id=m.signal_id
WHERE m.device_id IN (@d1,@d2) AND s.signal_key IN ('load_power','battery_soc')
AND (m.quality<>'generated' OR m.ingest_source<>'rakurs_preview_history' OR m.raw_value IS NOT NULL);
INSERT INTO shared_assert VALUES(IF(@foreign_rows=0,1,NULL));
SELECT COUNT(*) INTO @pairs FROM rakurs_samples a
JOIN rakurs_samples b ON b.device_id=@d2 AND b.signal_id=a.signal_id AND b.observed_at_utc=a.observed_at_utc
JOIN rakurs_signals s ON s.id=a.signal_id
WHERE a.device_id=@d1 AND s.signal_key IN ('load_power','battery_soc')
AND a.value_decimal IS NOT NULL AND b.value_decimal IS NOT NULL;
SELECT COUNT(*) INTO @conflicts FROM rakurs_samples a
JOIN rakurs_samples b ON b.device_id=@d2 AND b.signal_id=a.signal_id AND b.observed_at_utc=a.observed_at_utc
JOIN rakurs_signals s ON s.id=a.signal_id
WHERE a.device_id=@d1 AND s.signal_key IN ('load_power','battery_soc')
AND a.value_decimal IS NOT NULL AND b.value_decimal IS NOT NULL AND a.value_decimal<>b.value_decimal;
INSERT INTO shared_assert VALUES(IF(@pairs>0,1,NULL));
SELECT @pairs AS matched_numeric_pairs,@conflicts AS differing_pairs_before,
 @before_count-2*@pairs AS rows_without_numeric_pair;
UPDATE rakurs_samples b
JOIN rakurs_samples a ON a.device_id=@d1 AND a.signal_id=b.signal_id AND a.observed_at_utc=b.observed_at_utc
JOIN rakurs_signals s ON s.id=b.signal_id
SET b.value_decimal=a.value_decimal
WHERE b.device_id=@d2 AND s.signal_key IN ('load_power','battery_soc')
 AND a.quality='generated' AND b.quality='generated'
 AND a.ingest_source='rakurs_preview_history' AND b.ingest_source='rakurs_preview_history'
 AND a.raw_value IS NULL AND b.raw_value IS NULL
 AND a.value_decimal IS NOT NULL AND b.value_decimal IS NOT NULL AND a.value_decimal<>b.value_decimal;
SET @changed=ROW_COUNT();
SELECT COUNT(*) INTO @remaining FROM rakurs_samples a
JOIN rakurs_samples b ON b.device_id=@d2 AND b.signal_id=a.signal_id AND b.observed_at_utc=a.observed_at_utc
JOIN rakurs_signals s ON s.id=a.signal_id
WHERE a.device_id=@d1 AND s.signal_key IN ('load_power','battery_soc')
AND a.value_decimal IS NOT NULL AND b.value_decimal IS NOT NULL AND a.value_decimal<>b.value_decimal;
SELECT COUNT(*) INTO @after_count FROM rakurs_samples m JOIN rakurs_signals s ON s.id=m.signal_id
WHERE m.device_id IN (@d1,@d2) AND s.signal_key IN ('load_power','battery_soc');
INSERT INTO shared_assert VALUES(IF(@remaining=0 AND @changed=@conflicts AND @after_count=@before_count,1,NULL));
COMMIT;
SELECT 'SHARED_ARCHIVE_SYNC=PASS' AS result,@changed AS changed_rows,@remaining AS remaining_conflicts,
 @before_count AS rows_before,@after_count AS rows_after,@before_count-2*@pairs AS rows_without_numeric_pair;
